import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import ts from 'typescript';
const base = new URL('../', import.meta.url);
const source = (await readFile(new URL('../../functions/src/modules/securityObservation/publisher.ts', base), 'utf8')).replace(/\r\n/g, '\n');
const manifest = JSON.parse(await readFile(new URL('publisher-manifest.json', base), 'utf8'));
if (manifest.schema !== 'PAY0-OBSERVATION-PUBLISHER@1' || createHash('sha256').update(source).digest('hex') !== manifest.sha256) throw Error('PUBLISHER_REVIEW_REQUIRED');
const ast = ts.createSourceFile('publisher.ts', source, ts.ScriptTarget.ES2022, true);
for (const statement of ast.statements) if (ts.isImportDeclaration(statement) && statement.moduleSpecifier.text !== 'node:crypto') throw Error('NON_ISOLATED_PUBLISHER_IMPORT');
const result = ts.transpileModule(source, { reportDiagnostics: true, compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } });
if (result.diagnostics?.length) throw Error('PUBLISHER_TRANSPILE_FAILED');
await mkdir(new URL('.build/', base), { recursive: true });
await writeFile(new URL('.build/publisher.cjs', base), result.outputText);
console.log('PUBLISHER_BUILD_PASS');
