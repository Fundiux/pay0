const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
if (!/^127\.0\.0\.1:\d+$/.test(process.env.FIRESTORE_EMULATOR_HOST || '') || !/^demo-pay0-e1-/.test(process.env.GCLOUD_PROJECT || '')) throw Error('Isolated demo emulator required');
const dir = path.resolve(__dirname, '../../.firebase/modular-release/new-recovery-review');
const input = JSON.parse(fs.readFileSync(path.join(dir, 'input.json')));
const runtime = path.join(dir, 'runtime');
assert.equal(crypto.createHash('sha256').update(fs.readFileSync(input.archive)).digest('hex'), input.archiveSha256);
assert.equal(crypto.createHash('sha256').update(fs.readFileSync(path.join(runtime, input.patch.newModule))).digest('hex'), input.patch.newModuleSha256);
const handlers = require(path.join(runtime, input.patch.newModule));
const admin = require(path.join(runtime, 'node_modules/firebase-admin'));
const db = admin.firestore();
const req = (uid, data = {}) => ({ auth: { uid, token: {} }, data });
const deny = fn => assert.rejects(fn, e => e.code === 'permission-denied');
(async () => {
  await db.doc('users/reviewer').set({ role: 'superadmin', rootId: 'review-root', active: true });
  await db.doc('users/foreign').set({ role: 'superadmin', rootId: 'foreign-root', active: true });
  await db.doc('users/operator').set({ role: 'operador', rootId: 'review-root', active: true });
  await db.doc('users/disabled').set({ role: 'superadmin', rootId: 'review-root', active: false });
  const rootEmpty = await handlers.listOperationRecoveryReviews.run(req('reviewer'));
  assert.deepEqual(rootEmpty.rows, []);
  await assert.rejects(handlers.listOperationRecoveryReviews.run({ data: {} }), e => e.code === 'unauthenticated');
  await deny(handlers.listOperationRecoveryReviews.run(req('operator')));
  await deny(handlers.listOperationRecoveryReviews.run(req('disabled')));
  const batch = db.batch();
  for (let i = 0; i < 54; i++) batch.set(db.doc(`operationRecoveryJobs/${i.toString(16).padStart(64, '0')}`), { rootId: 'review-root', solicitudId: `fixture-${i}`, kind: 'MATERIALITY', status: 'NEEDS_REVIEW', attempts: 5, lastErrorCode: 'SYNTHETIC' });
  await batch.commit();
  const first = await handlers.listOperationRecoveryReviews.run(req('reviewer'));
  const second = await handlers.listOperationRecoveryReviews.run(req('reviewer', { cursor: first.nextCursor }));
  assert.equal(first.rows.length, 50); assert.equal(second.rows.length, 4);
  assert.equal(new Set([...first.rows, ...second.rows].map(r => r.id)).size, 54);
  const jobId = first.rows[0].id, job = db.doc(`operationRecoveryJobs/${jobId}`), original = (await job.get()).data();
  const results = await Promise.all(Array.from({ length: 6 }, () => handlers.acknowledgeOperationRecoveryReview.run(req('reviewer', { jobId, note: 'Acuse de revisión; no reintentar.' }))));
  assert.equal(results.filter(r => r.created).length, 1);
  assert.deepEqual((await job.get()).data(), original);
  assert.equal((await db.doc(`operationRecoveryReviews/${jobId}`).get()).get('action'), 'ACKNOWLEDGED_ONLY');
  assert.equal((await db.collection('pay0ActivityLog').where('event', '==', 'OPERACION_RECUPERACION_REVISADA').get()).size, 1);
  const listedAgain = await handlers.listOperationRecoveryReviews.run(req('reviewer'));
  assert.equal(listedAgain.rows.find(r => r.id === jobId).acknowledged, true);
  await deny(handlers.acknowledgeOperationRecoveryReview.run(req('foreign', { jobId, note: 'Cross-root denied' })));
  await deny(handlers.listOperationRecoveryReviews.run(req('foreign', { cursor: jobId })));
  assert.deepEqual((await handlers.listOperationRecoveryReviews.run(req('foreign'))).rows, []);
  await assert.rejects(handlers.acknowledgeOperationRecoveryReview.run(req('reviewer', { jobId, note: 'x'.repeat(501) })), e => e.code === 'invalid-argument');
  await job.update({ status: 'COMPLETED' });
  await assert.rejects(handlers.acknowledgeOperationRecoveryReview.run(req('reviewer', { jobId, note: 'Invalid terminal' })), e => e.code === 'failed-precondition');
  await db.doc('users/reviewer').update({ active: false });
  await deny(handlers.acknowledgeOperationRecoveryReview.run(req('reviewer', { jobId: first.rows[1].id, note: 'Revoked access' })));
  assert.equal((await db.collection('operationRecoveryReviews').get()).size, 1);
  for (const collection of ['pagos', 'walletEntries', 'clientDispersions', 'solicitudes']) assert.equal((await db.collection(collection).get()).size, 0);
  const proof = { status: 'PASS', archiveSha256: input.archiveSha256, persistence: 'REAL_ISOLATED_FIRESTORE_EMULATOR', authorizationPositiveAndNegative: true, revocationDenied: true, foreignRootsIsolated: true, emptyListClosed: true, concurrentAcknowledgeOnce: true, paginationBeyond50: true, sourceJobPreserved: true, financialWrites: 0, productionWrites: 0, checkedAt: new Date().toISOString() };
  fs.writeFileSync(path.join(dir, 'behavior-verification.json'), JSON.stringify(proof, null, 2));
  console.log(JSON.stringify(proof));
})().catch(e => { console.error(e); process.exitCode = 1; }).finally(() => db.terminate());
