const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const ts = require("../../functions/node_modules/typescript");
const source = fs.readFileSync(path.join(__dirname, "../../functions/src/modules/commissionDistributions/clientAllocation.ts"), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const moduleExports = {};
vm.runInNewContext(compiled, { exports: moduleExports, BigInt, Number, String, Set, Error, Array });
const calculate = moduleExports.calculateClientCommissionInstructions;
const base = { earnedMinor: 100000, operationBaseMinor: 10000000, contractRateBps: 100 };
const result = calculate({ ...base, instructions: [{ accountId: "bbva", pointsBps: 20 }, { accountId: "santander", earningsPercentBps: 5000 }] });
assert.equal(result.distributedMinor, 70000);
assert.equal(result.remainingMinor, 30000);
assert.equal(result.instructions[0].amountMinor, 20000);
assert.equal(result.instructions[1].amountMinor, 50000);
assert.equal(calculate({ ...base, instructions: [] }).remainingMinor, 100000);
assert.throws(() => calculate({ ...base, instructions: [{ accountId: "a", pointsBps: 20, earningsPercentBps: 5000 }] }));
assert.throws(() => calculate({ ...base, instructions: [{ accountId: "a", pointsBps: 101 }] }));
assert.throws(() => calculate({ ...base, instructions: [{ accountId: "a", earningsPercentBps: 10000 }, { accountId: "b", pointsBps: 1 }] }));
assert.throws(() => calculate({ ...base, operationBaseMinor: null, instructions: [{ accountId: "a", pointsBps: 20 }] }));
assert.throws(() => calculate({ ...base, instructions: [{ accountId: "a", earningsPercentBps: 10 }, { accountId: "a", earningsPercentBps: 20 }] }));
console.log("Client commission allocation tests passed.");
