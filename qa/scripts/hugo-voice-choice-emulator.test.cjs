const assert = require('node:assert/strict');
if (!/^127\.0\.0\.1:\d+$/.test(process.env.FIRESTORE_EMULATOR_HOST || '') || process.env.GCLOUD_PROJECT !== 'demo-pay0') throw Error('ISOLATED_FIRESTORE_EMULATOR_REQUIRED');
global.fetch = async () => { throw Error('EXTERNAL_NETWORK_FORBIDDEN'); };
const admin = require('../../functions/node_modules/firebase-admin');
if (!admin.apps.length) admin.initializeApp({ projectId: 'demo-pay0' });
const db = admin.firestore();
const { delegateHugoTeamVoiceTurn } = require('../../functions/lib/modules/agent007/teamCallables.js');
const uid = 'Ab4z0RttIqXbZFT0NuWsDjBkt6J2', rootId = 'voice-choice-test';
const auth = { uid, token: { role: 'superadmin' } };
let sequence = 0;
const ask = (request, sessionId = 'session-choice') => delegateHugoTeamVoiceTurn.run({ auth, data: { toolName: 'consultHugoTeam', request, sessionId, turnId: `turn-${++sequence}`, delegationId: `tool-${sequence}` } });

(async () => {
  await db.doc(`users/${uid}`).set({ role: 'superadmin', rootId, active: true });
  const sample = (id, company, date) => db.doc(`solicitudes/${id}`).set({ rootId, folio: `SCHOICE${id.toUpperCase()}`, status: 'PROCESANDO', companyName: company, clientName: 'CLIENTE PRUEBA', total: 7540, createdAt: admin.firestore.Timestamp.fromDate(new Date(date)) });
  await sample('a', 'ACIER CAPITAL', '2026-10-20T00:00:00Z');
  await sample('b', 'OTRA EMPRESA', '2026-10-19T00:00:00Z');
  const none = await ask('la segunda', 'empty-session');
  assert.equal(none.team.result, 'NEEDS_CLARIFICATION');
  const ambiguous = await ask('Consulta la solicitud por 7,540 pesos');
  assert.equal(ambiguous.team.result, 'NEEDS_CLARIFICATION');
  assert.match(ambiguous.text, /1\..*2\./);
  const otherSession = await ask('la segunda', 'different-session');
  assert.equal(otherSession.team.result, 'NEEDS_CLARIFICATION');
  const second = await ask('la segunda');
  assert.match(second.text, /OTRA EMPRESA/);
  assert.match(second.text, /no aparece una cotización activa/);
  const context = await ask('¿Y esta cotización?');
  assert.match(context.text, /OTRA EMPRESA/);
  const again = await ask('Consulta la solicitud por 7,540 pesos', 'session-first');
  assert.equal(again.team.result, 'NEEDS_CLARIFICATION');
  const first = await ask('la primera', 'session-first');
  assert.match(first.text, /ACIER CAPITAL/);
  const outOfRange = await ask('la quinta', 'session-first');
  assert.equal(outOfRange.team.result, 'NEEDS_CLARIFICATION');
  const stale = await ask('Consulta la solicitud por 7,540 pesos', 'stale-session');
  assert.equal(stale.team.result, 'NEEDS_CLARIFICATION');
  const staleTurn = await db.collection('hugoTeamTurns').where('voiceSessionId', '==', 'stale-session').get();
  await staleTurn.docs[0].ref.update({ createdAt: admin.firestore.Timestamp.fromMillis(Date.now() - 6 * 60_000) });
  assert.equal((await ask('la segunda', 'stale-session')).team.result, 'NEEDS_CLARIFICATION');
  await ask('Consulta la solicitud por 7,540 pesos', 'updated-session');
  await db.doc('solicitudes/b').update({ status: 'REVISADA' });
  assert.equal((await ask('la segunda', 'updated-session')).team.result, 'NEEDS_CLARIFICATION');
  await db.doc('solicitudes/b').update({ status: 'PROCESANDO' });
  await ask('Consulta la solicitud por 7,540 pesos', 'new-search-session');
  const unique = await ask('Consulta la solicitud de ACIER CAPITAL', 'new-search-session');
  assert.match(unique.text, /ACIER CAPITAL/);
  assert.equal((await ask('la segunda', 'new-search-session')).team.result, 'NEEDS_CLARIFICATION');
  await ask('Consulta la solicitud por 7,540 pesos', 'changed-session');
  await db.doc('solicitudes/b').update({ rootId: 'another-root' });
  assert.equal((await ask('la segunda', 'changed-session')).team.result, 'NEEDS_CLARIFICATION');
  await db.doc('solicitudes/b').update({ rootId });
  await ask('Consulta la solicitud por 7,540 pesos', 'deleted-session');
  await db.doc('solicitudes/b').delete();
  assert.equal((await ask('la segunda', 'deleted-session')).team.result, 'NEEDS_CLARIFICATION');
  await assert.rejects(() => delegateHugoTeamVoiceTurn.run({ auth: { uid: 'other-user', token: { role: 'superadmin' } }, data: { toolName: 'consultHugoTeam', request: 'la primera', sessionId: 'session-choice', turnId: 'unauthorized', delegationId: 'unauthorized' } }));
  console.log('VOICE_CHOICE_EMULATOR_PASS');
})().catch(error => { console.error(error); process.exitCode = 1; });
