import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { inspectIntegration, integrationSummary, moduleFor } from '../../scripts/inspect-modular-integration.mjs';

test('maps sensitive modules and preserves dependency boundaries', () => {
  assert.equal(moduleFor('firestore.rules'), 'access');
  assert.equal(moduleFor('functions/src/modules/clientDelegations/access.ts'), 'access');
  assert.equal(moduleFor('src/components/corporate-resources/DocumentDossier.tsx'), 'documents');
  assert.equal(moduleFor('functions/src/modules/pagos/receiptSemantics.ts'), 'pagos');
});
test('reports parallel dirty worktrees without reading secrets or changing work', t => {
  const base = fs.mkdtempSync(path.join(os.tmpdir(), 'pay0-integration-'));
  t.after(() => fs.rmSync(base, { recursive: true, force: true }));
  const cwd = path.join(base, 'candidate'), other = path.join(base, 'parallel');
  fs.mkdirSync(cwd);
  const git = (...args) => execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  git('init', '-b', 'main'); git('config', 'user.name', 'Fixture'); git('config', 'user.email', 'fixture@example.invalid');
  fs.mkdirSync(path.join(cwd, 'src/components'), { recursive: true });
  fs.writeFileSync(path.join(cwd, 'src/components/Panel.tsx'), 'original');
  git('add', '.'); git('commit', '-m', 'Base');
  git('worktree', 'add', '-b', 'parallel', other);
  fs.writeFileSync(path.join(cwd, 'src/components/Panel.tsx'), 'candidate');
  fs.writeFileSync(path.join(other, 'src/components/Panel.tsx'), 'parallel');
  fs.writeFileSync(path.join(other, '.env.local'), 'SECRET_VALUE_MUST_NOT_APPEAR');
  const before = git('status', '--porcelain');
  const report = inspectIntegration(cwd);
  const parallel = report.worktrees.find(row => row.branch === 'parallel');
  assert.equal(parallel.dirty, true); assert.equal(parallel.overlapCount, 1);
  assert.deepEqual(parallel.overlappingFiles, ['src/components/Panel.tsx']);
  assert.equal(JSON.stringify(report).includes('SECRET_VALUE'), false);
  assert.equal(JSON.stringify(report).includes('.env.local'), false);
  assert.equal(git('status', '--porcelain'), before);
  fs.writeFileSync(path.join(other, 'src/components/Panel.tsx'), 'parallel modified');
  assert.notEqual(inspectIntegration(cwd).worktrees.find(row => row.branch === 'parallel').snapshotSha256, parallel.snapshotSha256);
  assert.equal(integrationSummary(report).worktrees.some(row => 'dirtyFiles' in row), false);
  assert.equal(report.publication, 'NOT_ATTESTED');
});
