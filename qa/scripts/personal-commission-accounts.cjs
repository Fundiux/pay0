const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const ts = require("../../functions/node_modules/typescript");
const source = fs.readFileSync(path.join(__dirname, "../../functions/src/modules/commissionDistributions/personalAccounts.ts"), "utf8");
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const moduleExports = {};
vm.runInNewContext(output, { exports: moduleExports, String, Error });
const { normalizePersonalCommissionAccount, canUsePersonalCommissionAccount, maskPersonalCommissionInstrument } = moduleExports;
const input = { ownerUid: "owner1", rootId: "root1", bankName: "Banco", beneficiaryName: "Titular", instrumentType: "CLABE", instrumentNumber: "123456789012345678" };
const account = { ...normalizePersonalCommissionAccount(input), id: "account1" };
assert.equal(account.iqLinkStatus, "PENDING");
assert.equal(maskPersonalCommissionInstrument(account), "••5678");
assert.equal(canUsePersonalCommissionAccount(account, { rootId: "root1", ownerUid: "owner1" }), false);
assert.equal(canUsePersonalCommissionAccount({ ...account, iqLinkStatus: "VERIFIED" }, { rootId: "root1", ownerUid: "owner1" }), true);
assert.equal(canUsePersonalCommissionAccount({ ...account, iqLinkStatus: "VERIFIED" }, { rootId: "root1", ownerUid: "other" }), false);
assert.equal(canUsePersonalCommissionAccount({ ...account, iqLinkStatus: "VERIFIED", active: false }, { rootId: "root1", ownerUid: "owner1" }), false);
assert.throws(() => normalizePersonalCommissionAccount({ ...input, instrumentNumber: "123" }));
assert.throws(() => normalizePersonalCommissionAccount({ ...input, bankName: "B".repeat(101) }));
assert.throws(() => normalizePersonalCommissionAccount({ ...input, beneficiaryName: "T".repeat(161) }));
assert.throws(() => normalizePersonalCommissionAccount({ ...input, bankName: "Banco" + String.fromCharCode(10) + "Otro" }));
assert.throws(() => normalizePersonalCommissionAccount({ ...input, instrumentType: "CARD", instrumentNumber: "123456" }));
console.log("Personal commission account validation tests passed.");
