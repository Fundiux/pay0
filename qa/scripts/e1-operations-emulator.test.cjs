const assert = require('node:assert/strict');
if (!/^127\.0\.0\.1:\d+$/.test(process.env.FIRESTORE_EMULATOR_HOST || '') || !/^demo-pay0-e1-/.test(process.env.GCLOUD_PROJECT || '')) throw Error('Isolated demo emulator required');
const admin = require('../../functions/node_modules/firebase-admin');
admin.initializeApp({ projectId: process.env.GCLOUD_PROJECT });
const db = admin.firestore();
const recovery = require('../../functions/lib/modules/controlCenter/recovery');
const fs = require('node:fs'), path = require('node:path'), { createRequire } = require('node:module');
const ts = require('../../functions/node_modules/typescript');
const reviewSource = fs.readFileSync(path.resolve(__dirname, '../../functions/src/modules/controlCenter/recoveryReviewCallables.ts'), 'utf8');
const reviewExports = {};
new Function('require', 'exports', ts.transpileModule(reviewSource, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText)(createRequire(path.resolve(__dirname, '../../functions/lib/modules/controlCenter/recoveryReviewCallables.js')), reviewExports);
async function run() {
  const rootId = 'e1-recovery-root', actorUid = 'e1-actor';
  const source = db.doc('solicitudes/e1-source');
  await db.doc(`users/${actorUid}`).set({ rootId, role: 'superadmin', active: true });
  const row = { rootId, createdBy: actorUid, status: 'PROCESANDO', materialitySyncStatus: 'ERROR', ocFiscalMetadataUploadId: 'generation-one' };
  await source.set(row);
  await Promise.all(Array.from({ length: 8 }, () => recovery.enqueueRecovery(source.id, row, 'MATERIALITY')));
  let jobs = await db.collection('operationRecoveryJobs').get();
  assert.equal(jobs.size, 1, 'concurrent enqueue must create one persisted job');
  const job = jobs.docs[0].ref;
  let calls = 0;
  // The worker's transactions and audit are real; domain side effect is a local synthetic handler.
  await Promise.all(Array.from({ length: 4 }, () => recovery.processRecoveryJobs(async () => { calls++; await new Promise(resolve => setTimeout(resolve, 40)); })));
  assert.equal(calls, 1);
  assert.equal((await job.get()).get('status'), 'COMPLETED');
  assert.equal((await job.get()).get('attempts'), 1);
  await recovery.enqueueRecovery(source.id, row, 'MATERIALITY');
  assert.equal((await job.get()).get('status'), 'COMPLETED', 'a repeated event cannot reopen a completed generation');
  await job.update({ status: 'PENDING', attempts: 4, nextAttemptAt: admin.firestore.Timestamp.fromMillis(1) });
  await recovery.processRecoveryJobs(async () => { throw Error('SYNTHETIC_TRANSIENT'); });
  const exhausted = await job.get();
  assert.equal(exhausted.get('status'), 'NEEDS_REVIEW');
  assert.equal(exhausted.get('attempts'), 5);
  assert.equal(exhausted.get('nextAttemptAt'), undefined);
  await recovery.enqueueRecovery(source.id, row, 'MATERIALITY');
  assert.equal((await job.get()).get('attempts'), 5);
  const auth = { uid: actorUid, token: {} };
  const request = data => ({ auth, data });
  const listed = await reviewExports.listOperationRecoveryReviews.run(request({}));
  assert.equal(listed.rows.length, 1);
  assert.equal(listed.rows[0].acknowledged, false);
  const original = (await job.get()).data();
  const acknowledgements = await Promise.all(Array.from({ length: 4 }, () => reviewExports.acknowledgeOperationRecoveryReview.run(request({ jobId: job.id, note: 'Revisar documento con el responsable, sin reintentar.' }))));
  assert.equal(acknowledgements.filter(result => result.created).length, 1);
  assert.deepEqual((await job.get()).data(), original, 'administrative acknowledgement preserves source evidence and retry state');
  assert.equal((await reviewExports.listOperationRecoveryReviews.run(request({}))).rows[0].acknowledged, true);
  await db.doc('users/foreign').set({ rootId: 'other-root', role: 'superadmin', active: true });
  await db.doc('users/operator').set({ rootId, role: 'operador', active: true });
  await assert.rejects(reviewExports.acknowledgeOperationRecoveryReview.run({ auth: { uid: 'foreign', token: {} }, data: { jobId: job.id, note: 'Invalid scope' } }), error => error.code === 'permission-denied');
  await assert.rejects(reviewExports.listOperationRecoveryReviews.run({ auth: { uid: 'operator', token: {} }, data: {} }), error => error.code === 'permission-denied');
  await assert.rejects(reviewExports.listOperationRecoveryReviews.run({ data: {} }), error => error.code === 'unauthenticated');
  await source.update({ deletedAt: admin.firestore.Timestamp.now() });
  await recovery.executeRecovery({ rootId, actorUid, solicitudId: source.id, kind: 'MATERIALITY', generation: row.ocFiscalMetadataUploadId });
  assert.equal((await source.get()).get('materialitySyncStatus'), 'ERROR', 'terminal source must not be changed');
  const audit = await db.collection('pay0ActivityLog').where('rootId', '==', rootId).get();
  const alternativeAudit = await db.collection('hugoActivityLog').where('rootId', '==', rootId).get();
  assert.ok(audit.size + alternativeAudit.size >= 3, 'real worker and acknowledgement audit must be persisted');
  assert.equal(audit.docs.filter(doc => doc.get('event') === 'OPERACION_RECUPERACION_REVISADA').length, 1);
  const uiJob = db.doc(`operationRecoveryJobs/${'b'.repeat(64)}`);
  await uiJob.set({ rootId, solicitudId: 'e1-ui-source', kind: 'CERTIFICATE', status: 'NEEDS_REVIEW', attempts: 5, lastErrorCode: 'UI_SYNTHETIC_REVIEW' });
  const { chromium, expect } = require('@playwright/test');
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage();
    await page.exposeFunction('qaCall', (name, data) => reviewExports[name].run(request(data || {})));
    await page.route('http://localhost/e1-review', route => route.fulfill({ contentType: 'text/html', body: '<html><body><div id="root"></div></body></html>' }));
    await page.goto('http://localhost/e1-review');
    await page.addScriptTag({ path: path.join(path.dirname(require.resolve('react')), 'umd/react.development.js') });
    await page.addScriptTag({ path: path.join(path.dirname(require.resolve('react-dom')), 'umd/react-dom.development.js') });
    const uiSource = 'import * as React from "react";\n' + fs.readFileSync(path.resolve(__dirname, '../../src/components/control-center/RecoveryReview.tsx'), 'utf8');
    const uiJs = ts.transpileModule(uiSource, { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.React, target: ts.ScriptTarget.ES2020, esModuleInterop: true } }).outputText;
    await page.evaluate(js => {
      const services = Object.fromEntries(['listOperationRecoveryReviews', 'acknowledgeOperationRecoveryReview'].map(name => [name, data => window.qaCall(name, data)]));
      const exports = {}; new Function('require', 'exports', js)(name => name === 'react' ? window.React : services, exports);
      window.ReactDOM.createRoot(document.getElementById('root')).render(window.React.createElement(exports.default));
    }, uiJs);
    await page.getByText('Revisión administrativa de recuperaciones', { exact: true }).click();
    await page.getByLabel('Acuerdo de revisión').fill('Responsable avisado; no ejecutar recuperación financiera.');
    await page.getByRole('button', { name: 'Registrar revisión sin reintentar' }).click();
    await expect(page.getByText('Revisión registrada: Responsable avisado; no ejecutar recuperación financiera.', { exact: true })).toBeVisible();
    assert.equal((await uiJob.get()).get('status'), 'NEEDS_REVIEW');
    assert.equal((await db.doc(`operationRecoveryReviews/${uiJob.id}`).get()).get('action'), 'ACKNOWLEDGED_ONLY');
    await page.screenshot({ path: path.join(process.env.TEMP, 'recovery-review.png'), fullPage: true });
  } finally { await browser.close(); }
  for (let i = 0; i < 52; i++) await db.doc(`operationRecoveryJobs/${i.toString(16).padStart(64, '0')}`).set({ rootId, solicitudId: `page-${i}`, kind: 'CERTIFICATE', status: 'NEEDS_REVIEW', attempts: 5 });
  const firstPage = await reviewExports.listOperationRecoveryReviews.run(request({}));
  assert.equal(firstPage.rows.length, 50); assert.ok(firstPage.nextCursor);
  const secondPage = await reviewExports.listOperationRecoveryReviews.run(request({ cursor: firstPage.nextCursor }));
  assert.equal(secondPage.rows.length, 4);
  assert.equal(new Set([...firstPage.rows, ...secondPage.rows].map(row => row.id)).size, 54);
  const foreignCursor = 'f'.repeat(64);
  await db.doc(`operationRecoveryJobs/${foreignCursor}`).set({ rootId: 'other-root', status: 'NEEDS_REVIEW' });
  await assert.rejects(reviewExports.listOperationRecoveryReviews.run(request({ cursor: foreignCursor })), error => error.code === 'permission-denied');
  await db.doc(`operationRecoveryJobs/${firstPage.nextCursor}`).update({ status: 'COMPLETED' });
  await assert.rejects(reviewExports.listOperationRecoveryReviews.run(request({ cursor: firstPage.nextCursor })), error => error.code === 'failed-precondition');
  console.log(JSON.stringify({ result: 'PASS', storage: 'REAL_ISOLATED_FIRESTORE_EMULATOR', domainSideEffect: 'SYNTHETIC_HANDLER', concurrentEnqueue: 8, concurrentWorkers: 4, workerCalls: calls, exhaustedAttempts: 5, concurrentAcknowledgements: 4, persistedAcknowledgements: 1 }));
}
run().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => db.terminate());
