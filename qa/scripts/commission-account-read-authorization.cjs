const assert = require("node:assert/strict");
const fs = require("node:fs"), path = require("node:path"), vm = require("node:vm");
const ts = require("../../functions/node_modules/typescript");
const source = fs.readFileSync(path.join(__dirname, "../../functions/src/modules/commissionDistributions/accountReadAuthorization.ts"), "utf8");
const exports = {};
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, { exports, Error });
const authorize = exports.authorizeCommissionAccountRead;
const owner = { uid: "owner", rootId: "root", active: true };
const self = { uid: "owner", rootId: "root", role: "operador", active: true };
assert.equal(authorize(self, owner, "SELF_PROFILE").ownerUid, "owner");
assert.throws(() => authorize({ ...self, uid: "other" }, owner, "SELF_PROFILE"));
assert.throws(() => authorize({ ...self, rootId: "other" }, owner, "CLIENT_COSTS"));
assert.throws(() => authorize({ ...self, active: false }, owner, "SELF_PROFILE"));
assert.throws(() => authorize({ ...self, uid: "admin", role: "admin" }, owner, "CLIENT_COSTS"));
assert.equal(authorize({ ...self, uid: "root", role: "superadmin" }, owner, "CLIENT_COSTS").ownerUid, "owner");
assert.throws(() => authorize({ ...self, uid: "root", role: "superadmin" }, { ...owner, active: false }, "CLIENT_COSTS"));
console.log("Commission account read authorization tests passed.");
