const assert = require('node:assert/strict');
if (!/^127\.0\.0\.1:\d+$/.test(process.env.FIRESTORE_EMULATOR_HOST || '') || process.env.GCLOUD_PROJECT !== 'demo-pay0') throw Error('Local demo-pay0 emulator required');
const admin = require('../../functions/node_modules/firebase-admin');
admin.initializeApp({projectId:'demo-pay0'});
const db = admin.firestore(), uid = `iq-followup-${Date.now()}`, rootId = uid, auth = {uid, token:{}};
const beneficiaries = require('../../functions/lib/modules/beneficiaries/callables.js');
const guard = require('../../functions/lib/modules/iq/dispersionDestinationGuard.js');
const followup = require('../../functions/lib/modules/paymentApplications/complementFollowup.js');
const hugo = require('../../functions/lib/modules/agent007/callables.js');
const invoke = (fn, data={}, who=auth) => fn.run({auth:who,data});
async function run() {
  await db.doc(`users/${uid}`).set({rootId,role:'superadmin',nombre:'Eduardo',userNumber:1,active:true});
  await db.doc(`clients/${uid}`).set({rootId,clientNumber:1,adminId:uid,active:true});
  const input = {clientId:uid,nombre:'204 PUBLICIDAD',methods:[{tipo:'DEBITO',bankCode:'012',bankName:'BBVA',clabe:'012000000000000001'}]};
  const results = await Promise.allSettled([invoke(beneficiaries.createClientBeneficiary,input),invoke(beneficiaries.createClientBeneficiary,input)]);
  assert.equal(results.filter(r=>r.status==='fulfilled').length,1,'concurrent account must not be reassigned');
  const methods = await db.collection('clientBeneficiaryMethods').where('rootId','==',rootId).get();
  assert.equal(methods.size,1);
  const created = results.find(r=>r.status==='fulfilled').value;
  const beneficiary = (await db.doc(`clientBeneficiaries/${created.beneficiaryId}`).get()).data();
  const client = (await db.doc(`clients/${uid}`).get()).data();
  const destination = {rootId,clientId:uid,beneficiaryId:created.beneficiaryId,dispersionId:'d1',client,beneficiary,method:methods.docs[0].data(),legs:[{rootId,clientId:uid,principalDispersionId:'d1'}]};
  guard.assertDispersionDestination(destination);
  assert.throws(()=>guard.assertDispersionDestination({...destination,method:{...destination.method,active:false}}));
  assert.throws(()=>guard.assertDispersionDestination({...destination,method:{...destination.method,rootId:'foreign'}}));
  assert.throws(()=>guard.assertDispersionDestination({...destination,legs:[{rootId,clientId:'another',principalDispersionId:'d1'}]}));
  const operator = `${uid}-operator`;
  await db.doc(`users/${operator}`).set({rootId,role:'admin',userNumber:2,active:true});
  await db.doc(`userClientAccess/${operator}/clients/${uid}`).set({rootId,clientId:uid,active:true,permissions:{view:true,operate:false,operateBeneficiarios:false}});
  await assert.rejects(invoke(beneficiaries.createClientBeneficiary,{...input,methods:[{...input.methods[0],clabe:'012000000000000002'}]},{uid:operator,token:{}}));
  await db.doc(`userClientAccess/${operator}/clients/${uid}`).update({'permissions.operate':true,'permissions.operateBeneficiarios':true});
  const delegated = await invoke(beneficiaries.createClientBeneficiary,{...input,methods:[{...input.methods[0],clabe:'012000000000000002'}]},{uid:operator,token:{}});
  assert.equal(delegated.ok,true,'authorized beneficiary delegation remains functional');

  const solicitudId=`${uid}-s`, pagoId=`${uid}-p`, applicationId=`${uid}-ap`;
  await db.doc(`solicitudes/${solicitudId}`).set({rootId,folio:'S1C35U1E28',iqFolio:'100',facturaUuid:'11111111-1111-4111-8111-111111111111',status:'PROCESANDO',monto:116,createdAt:new Date('2020-01-01')});
  await db.doc(`pagos/${pagoId}`).set({rootId,folio:'P1C35U1E28',createdAt:new Date()});
  const appRef=db.doc(`pagoAplicaciones/${applicationId}`);
  await appRef.set({rootId,solicitudId,pagoId,folio:'AP1',invoiceType:'PPD',status:'APLICADA',montoAplicado:58,numeroParcialidad:1,saldoAnterior:116,saldoInsoluto:58,createdAt:new Date()});
  await Promise.all([followup.reconcilePaymentComplement(applicationId),followup.reconcilePaymentComplement(applicationId)]);
  const reqRef=db.doc(`paymentComplementRequests/${followup.complementRequestId(rootId,applicationId)}`);
  assert.equal((await reqRef.get()).data().status,'WAITING_IQ_APPLICATION');
  assert.equal((await reqRef.get()).data().revision,1);
  await appRef.update({iqApplicationStatus:'IQ_APPLIED',iqActionExecuted:true,iqApplicationId:'IQ-TEST'});
  await followup.reconcilePaymentComplement(applicationId);
  assert.equal((await reqRef.get()).data().status,'PENDING_PROVIDER_CONTRACT');
  assert.equal((await reqRef.get()).data().externalRequestSent,false);
  await appRef.update({status:'CANCELADA'}); await followup.reconcilePaymentComplement(applicationId);
  assert.equal((await reqRef.get()).data().status,'VOIDED');
  const deletedData=(await appRef.get()).data(); await appRef.delete();
  await followup.reconcilePaymentComplement(applicationId,deletedData);
  assert.equal((await reqRef.get()).data().status,'VOIDED');
  await appRef.set(deletedData);
  await appRef.update({status:'APLICADA',invoiceType:'PUE'}); await followup.reconcilePaymentComplement(applicationId);
  assert.equal((await reqRef.get()).data().status,'VOIDED');
  await appRef.update({invoiceType:'PPD'}); await db.doc(`solicitudes/${solicitudId}`).update({rootId:'foreign'});
  await assert.rejects(followup.reconcilePaymentComplement(applicationId),/SCOPE/);
  await db.doc(`solicitudes/${solicitudId}`).update({rootId});
  await assert.rejects(invoke(followup.listPaymentComplementFollowup,{}, {uid:operator,token:{role:'superadmin'}}));

  const batch=db.batch();
  for(let i=0;i<125;i++) {
    batch.set(db.doc(`agent007Messages/${uid}-${String(125-i).padStart(3,'0')}`),{rootId,conversationId:`${rootId}_${uid}`,role:'assistant',recipientUid:uid,read:false,text:`message-${i}`,createdAt:admin.firestore.Timestamp.fromMillis(1700000000000+i)});
    batch.set(db.doc(`solicitudes/${uid}-noise-${i}`),{rootId,folio:`S${1000+i}C1U1E1`,createdAt:new Date()});
  }
  await batch.commit();
  await db.doc(`agent007Messages/${uid}-foreign`).set({rootId:'foreign',conversationId:`${rootId}_${uid}`,role:'assistant',text:'MUST_NOT_LEAK',createdAt:new Date()});
  const listed=await invoke(hugo.listAgent007Messages);
  assert.equal(listed.messages.length,80);
  assert(listed.messages.some(row=>row.text==='message-124'));
  assert(!listed.messages.some(row=>row.text==='MUST_NOT_LEAK'));
  const answer=await invoke(hugo.sendAgent007Message,{text:'Revisa S1C35U1E28'});
  assert.match(answer.message.text,/S1C35U1E28/);
  assert.match(answer.message.text,/PROCESANDO/);
  const pending=await invoke(hugo.sendAgent007Message,{text:'¿Ya solicitaste los complementos a IQ?'});
  assert.match(pending.message.text,/no están conectadas|aún no/);
  console.log(JSON.stringify({ok:true,checks:['beneficiary business name with digits','concurrent account uniqueness','read-only delegation denied','dispersion destination scope and active status','PPD followup idempotency','IQ confirmation required','no fake external requests','PUE and cancellation','foreign root denied','latest 80 messages','old folio exact lookup','Hugo truthful integration capabilities'],externalActions:0}));
}
run().then(()=>process.exit(0)).catch(e=>{console.error(e);process.exit(1)});
