const assert = require('node:assert/strict');
if (!/^127\.0\.0\.1:\d+$/.test(process.env.FIRESTORE_EMULATOR_HOST || '') || process.env.GCLOUD_PROJECT !== 'demo-pay0') throw Error('Local emulator required');
global.fetch = async () => { throw Error('EXTERNAL_NETWORK_FORBIDDEN'); };
const admin = require('../../functions/node_modules/firebase-admin');
admin.initializeApp({ projectId: 'demo-pay0' });
const db = admin.firestore();
const { Pay0Connector } = require('../../functions/lib/modules/agent007/pay0Connector');
const callables = require('../../functions/lib/modules/agent007/callables');
const { reconcileForPay0Change } = require('../../functions/lib/modules/agent007/reconciliationMaintenance');
const { purgeExpiredHugoTraces } = require('../../functions/lib/modules/agent007/traceStore');
const rootId = `hugo-phase2-${Date.now()}`;
const auth = { uid: rootId, token: { role: 'superadmin' } };

async function main() {
  await db.doc(`users/${rootId}`).set({ role: 'superadmin', rootId, active: true, email: 'synthetic@example.test' });
  await db.doc(`solicitudes/${rootId}-sol`).set({ rootId, folio: 'S12345', status: 'PROCESANDO', amount: 120, createdAt: admin.firestore.Timestamp.now() });
  await db.doc(`paymentComplementConfigs/${rootId}`).set({ rootId, iqLookupEnabled: true, iqEnabled: true, iqRequestEnabled: true });
  await db.doc(`iqIntegrationConfigs/${rootId}`).set({ rootId, enabled: true, automation: { aplicacionPagos: true } });
  const connector = new Pay0Connector(db, { uid: rootId, rootId, role: 'superadmin' });
  const capabilities = await connector.getIqCapabilities();
  assert.equal(capabilities.completeness, 'COMPLETE');
  assert.equal(capabilities.evidence.length, 2);
  assert.equal(capabilities.data.consultaComplemento, 'HABILITADA_SUJETA_A_PERFIL_PERMISOS_Y_CUOTA');
  const before = (await db.doc(`solicitudes/${rootId}-sol`).get()).data();
  const answer = await callables.sendAgent007Message.run({ auth, data: { text: '¿Qué pasó con S12345?' } });
  assert.match(answer.message.text, /S12345/);
  const traces = await db.collection('agent007Traces').where('rootId', '==', rootId).get();
  assert.equal(traces.size, 1);
  const trace = traces.docs[0].data();
  assert.equal(trace.channel, 'WEB');
  assert.equal(trace.promptVersion, 'legacy-v1');
  assert.equal(trace.resultStatus, 'DETERMINISTIC_FALLBACK');
  assert(trace.toolsRequested.includes('getIqCapabilities'));
  assert(trace.toolsRequested.includes('getSolicitud'));
  assert(trace.evidenceReferences.some(row => row.entityType === 'solicitud'));
  assert(trace.expiresAt.toMillis() > Date.now());
  assert.doesNotMatch(JSON.stringify(trace), /¿Qué pasó|synthetic@example/);
  const after = (await db.doc(`solicitudes/${rootId}-sol`).get()).data();
  assert.deepEqual(after, before, 'conversation read did not mutate PAY0 state');
  const conversation = (await db.doc(`agent007Conversations/${rootId}_${rootId}`).get()).data();
  assert(conversation.recentEntities.some(row => row.folio === 'S12345'));
  assert.equal(await reconcileForPay0Change('solicitud', before, { ...before }), 0);
  assert.equal(await reconcileForPay0Change('solicitud', before, { ...before, rootId: 'foreign-root', facturaUuid: 'x' }), 0);
  await db.doc(`agent007Recommendations/${rootId}-rec`).set({ rootId, kind: 'OC_FISCAL_REVIEW', caseId: `${rootId}-sol`, proposal: 'Revisar', status: 'PENDING_REVIEW', createdAt: admin.firestore.Timestamp.now() });
  await db.doc(`solicitudes/${rootId}-sol`).update({ facturaUuid: 'synthetic-uuid' });
  const changed = await reconcileForPay0Change('solicitud', before, { ...before, facturaUuid: 'synthetic-uuid' });
  assert.equal(changed, 1);
  assert.equal((await db.doc(`agent007Recommendations/${rootId}-rec`).get()).data().status, 'SUPERSEDED');
  await db.doc(`agent007Traces/${rootId}-expired`).set({ rootId, expiresAt: new Date(0) });
  await purgeExpiredHugoTraces.run({});
  assert.equal((await db.doc(`agent007Traces/${rootId}-expired`).get()).exists, false);
  assert.equal((await db.doc(traces.docs[0].ref.path).get()).exists, true);
  console.log(JSON.stringify({ ok: true, traces: traces.size, readBusinessWrites: 0, maintenanceWrites: changed, source: trace.resultStatus }));
}
main().then(() => process.exit(0)).catch(error => { console.error(error); process.exit(1); });
