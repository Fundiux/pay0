const assert = require("node:assert/strict");
if (!/^127\.0\.0\.1:\d+$/.test(process.env.FIRESTORE_EMULATOR_HOST || "") || !/^127\.0\.0\.1:\d+$/.test(process.env.FIREBASE_STORAGE_EMULATOR_HOST || "") || process.env.GCLOUD_PROJECT !== "demo-pay0") throw Error("ISOLATED_FIREBASE_EMULATORS_REQUIRED");
global.fetch = async () => { throw Error("EXTERNAL_NETWORK_FORBIDDEN"); };
const admin = require("../../functions/node_modules/firebase-admin");
if (!admin.apps.length) admin.initializeApp({ projectId: "demo-pay0", storageBucket: "demo-pay0.appspot.com" });
const db = admin.firestore();
const ExcelJS = require("exceljs");
const { routeTeamTurn } = require("../../functions/lib/modules/agent007/teamRouting.js");
const { sendHugoTeamTurn, listHugoTeamTurns } = require("../../functions/lib/modules/agent007/teamCallables.js");
const uid = "Ab4z0RttIqXbZFT0NuWsDjBkt6J2", rootId = "root-hugo-team";
const auth = value => ({ uid: value, token: { role: "superadmin" } });
const turnId = number => `00000000-0000-4000-8000-${String(number).padStart(12, "0")}`;

(async () => {
  assert.equal(routeTeamTurn("Hugo, pregúntale a Sofía por esta OC").agent, "sofia");
  assert.equal(routeTeamTurn("Regresa con Hugo", "maria").agent, "hugo");
  assert.deepEqual(routeTeamTurn("¿Por qué falta la cotización?", "hugo").consulted, ["sofia", "maria"]);
  await db.doc(`users/${uid}`).set({ role: "superadmin", rootId, active: true });
  await db.doc("users/other-superadmin").set({ role: "superadmin", rootId, active: true });
  await db.doc("solicitudes/sol-team").set({ rootId, folio: "S1C19U3E2", status: "PROCESANDO", companyName: "ACIER CAPITAL", clientName: "Cliente prueba", total: 7540, moneda: "MXN", createdAt: admin.firestore.Timestamp.now() });
  const book = new ExcelJS.Workbook(), sheet = book.addWorksheet("OC");
  sheet.getRow(1).values = ["Moneda", "MXN - Pesos Mexicanos"];
  sheet.getRow(2).values = ["Razon Social:", "Cliente de prueba"];
  sheet.getRow(3).values = ["RFC:", "XAXX010101000"];
  sheet.getRow(4).values = ["Cantidad", "Clave Unidad", "Clave Concepto", "Concepto", "Precio unitario", "Importe"];
  sheet.getRow(5).values = [1, "", "", "Servicio comercial", 6500, 6500];
  sheet.getRow(6).values = ["Subtotal:", 6500]; sheet.getRow(7).values = ["IVA:", 1040]; sheet.getRow(8).values = ["TOTAL:", 7540];
  const bytes = Buffer.from(await book.xlsx.writeBuffer());
  const storagePath = `roots/${rootId}/solicitudes/sol-team/docs/ORDEN_COMPRA/oc-team-synthetic.xlsx`;
  await admin.storage().bucket().file(storagePath).save(bytes);
  await db.doc("uploads/oc-team").set({ rootId, solicitudId: "sol-team", active: true, status: "READY", documentType: "ORDEN_COMPRA", storagePath });
  const input = { agent: "hugo", channel: "TEXT", message: "¿Por qué falta la cotización de S1C19U3E2?", turnId: turnId(1) };
  const first = await sendHugoTeamTurn.run({ auth: auth(uid), data: input });
  assert.equal(first.result, "READ_COMPLETE");
  assert.deepEqual(first.consultedAgents, ["sofia", "maria"]);
  assert.match(first.reply, /Hugo consultó a Sofía y María/);
  assert.match(first.reply, /S1C19U3E2/);
  assert.equal(first.evidence.some(row => row.kind === "ORDEN_COMPRA"), true);
  assert.deepEqual(first.toolsUsed, ["getSolicitud", "listSolicitudUploads", "getQuotationJob"]);
  const repeated = await sendHugoTeamTurn.run({ auth: auth(uid), data: input });
  assert.equal(repeated.reply, first.reply);
  await assert.rejects(() => sendHugoTeamTurn.run({ auth: auth(uid), data: { ...input, message: "Otra petición" } }));
  assert.equal((await db.collection("hugoTeamTurns").get()).size, 1);
  const analyzed = await sendHugoTeamTurn.run({ auth: auth(uid), data: { agent: "sofia", channel: "TEXT", message: "Sofía, analiza la OC de S1C19U3E2", turnId: turnId(6) } });
  assert.match(analyzed.reply, /1 partida\(s\)/);
  assert.match(analyzed.reply, /Servicio comercial/);
  assert.equal(analyzed.evidence.some(row => row.kind === "OC_CONTENIDO_LEIDO"), true);
  assert.equal(analyzed.toolsUsed.includes("parseOcCommercialMetadataBuffer"), true);
  const preview = await sendHugoTeamTurn.run({ auth: auth(uid), data: { agent: "maria", channel: "AUDIO", message: "Corrige esta Solicitud", turnId: turnId(2) } });
  assert.equal(preview.result, "NO_EXECUTION");
  assert.equal(preview.action, "PENDING_AUTHORIZATION");
  assert.deepEqual(preview.toolsUsed, []);
  assert.equal((await db.doc("solicitudes/sol-team").get()).get("status"), "PROCESANDO");
  assert.equal((await listHugoTeamTurns.run({ auth: auth(uid), data: { agent: "hugo" } })).turns.length, 1);
  await assert.rejects(() => sendHugoTeamTurn.run({ auth: auth("other-superadmin"), data: { ...input, turnId: turnId(3) } }));
  await assert.rejects(() => sendHugoTeamTurn.run({ auth: null, data: { ...input, turnId: turnId(5) } }));
  await db.doc(`users/${uid}`).update({ active: false });
  await assert.rejects(() => sendHugoTeamTurn.run({ auth: auth(uid), data: { ...input, turnId: turnId(4) } }));
  assert.equal((await db.collection("hugoTeamTurns").get()).size, 3);
  console.log("PASS team routing, delegated read, evidence, idempotency, audio write block, owner and revoked authorization");
})().catch(error => { console.error(error); process.exitCode = 1; });
