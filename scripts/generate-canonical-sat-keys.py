"""Regenerate the compact CFDI 4.0 key snapshot from PAY0's pinned SAT package."""

import base64
import bz2
import hashlib
import pathlib
import sqlite3
import zlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/canonicos/formatos/catalogos SAT/catalogs.db.bz2"
TARGET = ROOT / "functions/src/modules/facturama/canonicalSatKeys.generated.ts"
EXPECTED_SOURCE_SHA256 = "394e8b1e5409a2ba2728cc6d00fdfa4f2417c0f7b4710e3d9c435163da57f245"

source = SOURCE.read_bytes()
actual_hash = hashlib.sha256(source).hexdigest()
if actual_hash != EXPECTED_SOURCE_SHA256:
    raise SystemExit("SAT source hash changed; review the new source before regenerating")

db = sqlite3.connect(":memory:")
db.deserialize(bz2.decompress(source))
products = [row[0] for row in db.execute("SELECT id FROM cfdi_40_productos_servicios ORDER BY id")]
units = [row[0] for row in db.execute("SELECT id FROM cfdi_40_claves_unidades ORDER BY id")]
if len(products) != 52513 or len(units) != 2418 or any(len(code) != 8 for code in products):
    raise SystemExit("Unexpected SAT source structure or key count")

def encoded(text):
    return base64.b64encode(zlib.compress(text.encode("ascii"), level=9)).decode("ascii")

product_blob = encoded("".join(products))
unit_blob = encoded("\n".join(units))
TARGET.write_text(
    "// Generated by scripts/generate-canonical-sat-keys.py from the pinned CFDI 4.0 SAT package.\n"
    f'export const CANONICAL_SAT_SOURCE_SHA256 = "{actual_hash}";\n'
    f'export const CANONICAL_SAT_PRODUCT_COUNT = {len(products)};\n'
    f'export const CANONICAL_SAT_UNIT_COUNT = {len(units)};\n'
    f'export const CANONICAL_SAT_PRODUCTS_ZLIB_BASE64 = "{product_blob}";\n'
    f'export const CANONICAL_SAT_UNITS_ZLIB_BASE64 = "{unit_blob}";\n',
    encoding="utf-8",
)
print(f"Generated {len(products)} product keys and {len(units)} unit keys")
