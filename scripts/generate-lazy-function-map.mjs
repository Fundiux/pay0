// Generates functions/src/lazyModules.generated.ts: exported name -> module that defines it, read from the
// re-exports of functions/src/index.ts. Run with --check to fail when the committed file is stale.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const root = path.resolve(import.meta.dirname, '..');
const require = createRequire(path.join(root, 'functions/package.json'));
const ts = require('typescript');
const indexPath = path.join(root, 'functions/src/index.ts');
const outPath = path.join(root, 'functions/src/lazyModules.generated.ts');

export function buildMap(source = fs.readFileSync(indexPath, 'utf8')) {
  const file = ts.createSourceFile('index.ts', source, ts.ScriptTarget.Latest, true);
  const map = {};
  for (const statement of file.statements) {
    if (ts.isExportDeclaration(statement)) {
      if (!statement.moduleSpecifier || !statement.exportClause || !ts.isNamedExports(statement.exportClause)) throw Error('LAZY_MAP_UNSUPPORTED_EXPORT');
      const module = statement.moduleSpecifier.text;
      for (const element of statement.exportClause.elements) {
        if (statement.isTypeOnly || element.isTypeOnly) continue;
        const name = element.name.text;
        if (map[name]) throw Error(`LAZY_MAP_DUPLICATE_${name}`);
        map[name] = { module, export: (element.propertyName ?? element.name).text };
      }
    } else if (ts.isVariableStatement(statement) && statement.modifiers?.some(m => m.kind === ts.SyntaxKind.ExportKeyword)) {
      throw Error('LAZY_MAP_INLINE_EXPORT'); // every callable must live in a module
    } else if (ts.isExportAssignment(statement) || (ts.isFunctionDeclaration(statement) && statement.modifiers?.some(m => m.kind === ts.SyntaxKind.ExportKeyword))) {
      throw Error('LAZY_MAP_INLINE_EXPORT');
    }
  }
  return Object.fromEntries(Object.keys(map).sort().map(name => [name, map[name]]));
}

export function render(map) {
  const rows = Object.entries(map).map(([name, { module, export: exported }]) => `  ${name}: { module: ${JSON.stringify(module)}, export: ${JSON.stringify(exported)} },`);
  return `// Generated by scripts/generate-lazy-function-map.mjs from the re-exports of index.ts. Do not edit.\nexport const LAZY_MODULES: Record<string, { module: string; export: string }> = {\n${rows.join('\n')}\n};\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === import.meta.filename) {
  const text = render(buildMap());
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== text) { console.error('LAZY_MAP_STALE: run node scripts/generate-lazy-function-map.mjs'); process.exit(1); }
    console.log('LAZY_MAP_FRESH', Object.keys(buildMap()).length);
  } else {
    fs.writeFileSync(outPath, text);
    console.log('LAZY_MAP_WRITTEN', Object.keys(buildMap()).length);
  }
}
